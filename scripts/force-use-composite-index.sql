-- ============================================
-- 强制使用复合索引的查询优化
-- ============================================
-- 问题：PostgreSQL 查询优化器可能因为数据量小而不使用复合索引
-- 解决：检查查询计划，确保使用正确的索引

-- ============================================
-- 步骤 1: 查看当前查询计划
-- ============================================
-- 注意：需要替换 'YOUR_USER_ID' 为实际用户ID
-- 可以通过以下方式获取：SELECT auth.uid();

-- 查看查询计划（不执行）
EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT id, post_url, created_at, is_read, read_at
FROM favorites
WHERE user_id = auth.uid()
ORDER BY created_at DESC;

-- ============================================
-- 步骤 2: 检查为什么优化器不使用复合索引
-- ============================================
-- 可能的原因：
-- 1. 数据量太小（只有4条记录），优化器认为全表扫描或单列索引更快
-- 2. 统计信息不准确
-- 3. 查询条件不完全匹配索引

-- ============================================
-- 步骤 3: 更新统计信息（如果还没执行）
-- ============================================
ANALYZE favorites;

-- ============================================
-- 步骤 4: 检查表的数据量
-- ============================================
SELECT 
  COUNT(*) as total_records,
  COUNT(DISTINCT user_id) as unique_users
FROM favorites;

-- ============================================
-- 说明：
-- ============================================
-- 如果数据量很小（< 10条记录），PostgreSQL 可能选择：
-- 1. 使用 idx_favorites_user_id 找到所有记录
-- 2. 然后在内存中排序
-- 
-- 这通常比使用复合索引更快，因为：
-- - 索引查找需要额外的 I/O
-- - 对于小数据集，内存排序非常快
--
-- 当数据量增加到 100+ 条记录时，复合索引的优势会更明显


